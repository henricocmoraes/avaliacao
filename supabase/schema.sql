-- Supabase cloud schema for the Avaliação Física beta.
-- The app server must connect with a server-only Supabase secret key.
-- Do not put that key in public/ or in browser JavaScript.

create table if not exists public.clients (
  id bigint generated by default as identity primary key,
  name text not null,
  birth_date date,
  sex text,
  phone text,
  created_at timestamptz not null default now(),
  legacy_id bigint unique
);

create table if not exists public.evaluations (
  id bigint generated by default as identity primary key,
  client_id bigint not null references public.clients(id) on delete cascade,
  evaluated_on date not null,
  modules jsonb not null default '[]'::jsonb,
  payload jsonb not null default '{}'::jsonb,
  created_at timestamptz not null default now(),
  legacy_id bigint unique
);

create index if not exists evaluations_client_date_idx
  on public.evaluations (client_id, evaluated_on desc, id desc);

-- The current app has one owner protected by its server-side password login.
-- Browser clients must not query these tables directly. The API server uses
-- the Supabase secret key, kept in its private environment, to access them.
alter table public.clients enable row level security;
alter table public.evaluations enable row level security;

revoke all on public.clients from anon, authenticated;
revoke all on public.evaluations from anon, authenticated;
grant select, insert, update, delete on public.clients, public.evaluations to service_role;
grant usage, select on all sequences in schema public to service_role;
